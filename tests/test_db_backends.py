def test_placeholder_translation_skips_quoted_question_marks():
    sql = "SELECT '?' AS literal, 'it''s ?' AS other FROM t WHERE a = ? AND b = ?"
    assert translate_placeholders(sql) == (
        "SELECT '?' AS literal, 'it''s ?' AS other FROM t WHERE a = %s AND b = %s"
    )
    assert translate_placeholders("SELECT 'already %s', ?") == (
        "SELECT 'already %s', %s"
    )


def test_postgresql_executemany_uses_cursor():
    class Cursor:
        def executemany(self, statement, params_seq):
            self.statement = statement
            self.params_seq = params_seq
            return self

    class RawConnection:
        def cursor(self):
            self.last_cursor = Cursor()
            return self.last_cursor

    raw = RawConnection()
    conn = Connection(raw, Database.from_url("postgresql://localhost/schooltrack"))
    params = [("first", 1), ("second", 2)]

    result = conn.executemany("INSERT INTO items VALUES (?, ?)", params)

    assert result is raw.last_cursor
    assert raw.last_cursor.statement == "INSERT INTO items VALUES (%s, %s)"
    assert raw.last_cursor.params_seq == params


def test_postgresql_schema_uses_identity_and_portable_syntax():
    ddl = " ".join(migration_statements(1, "postgresql"))
    assert "GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert "AUTOINCREMENT" not in ddl
    assert "COLLATE NOCASE" not in ddl
    assert "CREATE TABLE IF NOT EXISTS purchases" in ddl
    assert "ON DELETE CASCADE" in ddl

    lower_index = " ".join(migration_statements(2, "postgresql"))
    assert "LOWER(name)" in lower_index
    assert "uq_suppliers_name_lower" in lower_index


def test_sqlite_schema_remains_supported():
    ddl = " ".join(migration_statements(1, "sqlite"))
    assert "AUTOINCREMENT" in ddl
    assert "GENERATED BY DEFAULT AS IDENTITY" not in ddl


def test_search_sql_is_portable_and_case_insensitive():
    where, params = _build_where(PurchaseFilters(search="Toner"))
    assert "LOWER(p.reference) LIKE LOWER(?)" in where
    assert "LOWER(s.name) LIKE LOWER(?)" in where
    assert "COLLATE NOCASE" not in where
    assert "ILIKE" not in where
    assert params == ["%Toner%", "%Toner%", "%Toner%", "%Toner%"]


def test_migration_runner_is_idempotent_and_preserves_rows(tmp_path: Path):
    db_path = tmp_path / "migrations.db"
    init_db(db_path)
    init_db(db_path)

    conn = connect(db_path)
    try:
        assert [row["version"] for row in conn.execute(
            "SELECT version FROM schema_migrations ORDER BY version"
        ).fetchall()] == [1, 2]
        assert conn.execute("PRAGMA user_version").fetchone()[0] == 2
    finally:
        conn.close()

    conn = connect(db_path)
    try:
        supplier = create_supplier(conn, SupplierCreate(**supplier_payload("Migration Supplier")))
        payload = PurchaseCreate(**purchase_payload(supplier["id"]))
        create_purchase(conn, payload)
    finally:
        conn.close()

    init_db(db_path)

    conn = connect(db_path)
    try:
        assert conn.execute("SELECT COUNT(*) AS n FROM suppliers").fetchone()["n"] == 1
        assert conn.execute("SELECT COUNT(*) AS n FROM purchases").fetchone()["n"] == 1
        assert conn.execute("SELECT COUNT(*) AS n FROM purchase_items").fetchone()["n"] == 2
    finally:
        conn.close()


def test_purchase_insert_rolls_back_header_and_items_together(tmp_path: Path):
    db_path = tmp_path / "rollback.db"
    init_db(db_path)
    conn = connect(db_path)
    try:
        supplier = create_supplier(conn, SupplierCreate(**supplier_payload("Rollback Supplier")))
        payload = PurchaseCreate(**purchase_payload(supplier["id"]))

        def fail_items(*_args, **_kwargs):
            raise RuntimeError("simulated line-item failure")

        conn.executemany = fail_items  # type: ignore[method-assign]
        with pytest.raises(RuntimeError):
            create_purchase(conn, payload)
    finally:
        conn.close()

    check = connect(db_path)
    try:
        assert check.execute("SELECT COUNT(*) AS n FROM purchases").fetchone()["n"] == 0
        assert check.execute("SELECT COUNT(*) AS n FROM purchase_items").fetchone()["n"] == 0
    finally:
        check.close()


def test_duplicate_supplier_error_helper_recognises_sqlite(tmp_path: Path):
    db_path = tmp_path / "unique.db"
    init_db(db_path)
    conn = connect(db_path)
    try:
        create_supplier(conn, SupplierCreate(**supplier_payload("Uniqueness Check")))
        with pytest.raises(ConflictError):
            create_supplier(conn, SupplierCreate(**supplier_payload("uniqueness check")))

        with pytest.raises(Exception) as exc_info:
            conn.execute(
                "INSERT INTO suppliers (name, created_at) VALUES (?, ?)",
                ("UNIQUENESS CHECK", "now"),
            )
        assert is_unique_violation(exc_info.value)
    finally:
        conn.close()
