def test_database_url_selection_and_redaction(tmp_path: Path):
    postgres = Database.from_url(
        "postgresql://schooltrack:super-secret@db.example.com:5432/schooltrack?sslmode=require"
    )
    assert postgres.backend == "postgresql"
    assert postgres.url.startswith("postgresql://")
    assert "super-secret" not in repr(postgres)
    assert "db.example.com" not in repr(postgres)

    legacy = Database.from_url("postgres://user:pass@localhost/schooltrack")
    assert legacy.url.startswith("postgresql://")

    sqlite_path = tmp_path / "url-selected.db"
    sqlite = Database.from_url(f"sqlite:///{sqlite_path.as_posix()}")
    assert sqlite.backend == "sqlite"
    assert str(sqlite.sqlite_path).endswith("url-selected.db")


